# Output format, for conditional content, e.g.:
#   if (render_target == "pdf") { ... } else { ... }
#   ::: {.content-visible when-format="html"}
render_target <- local({
  fmt <- knitr::opts_knit$get("rmarkdown.pandoc.to")
  if (is.null(fmt)) {
    "rstudio"
  } else if (fmt == "latex") {
    "pdf"
  } else if (startsWith(fmt, "html")) {
    "html"
  } else if (fmt == "docx") {
    "docx"
  } else {
    fmt
  }
})

# Fixed diagonal "DRAFT <version>" watermark for HTML output (PDF uses
# inc/title.tex). Call from a `results: asis` chunk:
#   draft_banner(params$is_draft, params$version)
# No-op for non-HTML targets or when is_draft is FALSE.
draft_banner <- function(is_draft, version, target = render_target) {
  if (!isTRUE(is_draft) || target != "html") {
    return(invisible(NULL))
  }
  cat(sprintf(
    paste0(
      "<style>\n",
      "body::before {\n",
      '  content: "DRAFT %s";\n',
      "  position: fixed;\n",
      "  top: 50%%;\n",
      "  left: 50%%;\n",
      "  transform: translate(-50%%, -50%%) rotate(-30deg);\n",
      "  font-size: 8rem;\n",
      "  color: rgba(241, 126, 0, 0.12);\n",
      "  z-index: -1;\n",
      "  pointer-events: none;\n",
      "  white-space: nowrap;\n",
      "}\n",
      "</style>\n"
    ),
    version
  ))
}

# ggsave() source-stamp mask ----
# Appends "Generated by: <relative path>" to the plot caption. Use
# ggplot2::ggsave() to bypass.
#
# Path resolution order:
#   1. `.generator` in a calling frame (explicit; set by save_figure());
#   2. knitr::current_input(dir = TRUE) (figure written from a rendering .qmd);
#   3. `.generator` in the global environment (script sourced top to bottom);
#   4. the RStudio source editor.
# The global comes after knitr because a loader script (e.g. _load.R under
# programs/<report>/04_analyse/) sources every file into one environment, so
# the global holds the last file sourced, not necessarily the one plotting.
# Without steps 1 and 3, a batch build (e.g. make_artifacts.R) would stamp
# "unknown" on every figure.

.as_project_path <- function(path) {
  if (!fs::is_absolute_path(path)) {
    return(as.character(fs::path_tidy(path)))
  }
  root <- tryCatch(here::here(), error = function(e) getwd())
  as.character(fs::path_rel(path, root))
}

.usable_path <- function(x) {
  is.character(x) && length(x) == 1L && !is.na(x) && nzchar(x)
}

.get_source_path <- function() {
  from_frame <- dynGet(".generator", ifnotfound = NULL, inherits = FALSE)
  if (.usable_path(from_frame)) {
    return(.as_project_path(from_frame))
  }
  knitr_input <- knitr::current_input(dir = TRUE)
  if (.usable_path(knitr_input)) {
    # Quarto hands knitr its intermediate <name>.rmarkdown, not the .qmd
    knitr_input <- sub("[.]rmarkdown$", ".qmd", knitr_input)
    return(.as_project_path(knitr_input))
  }
  from_global <- get0(".generator", envir = globalenv(), ifnotfound = NULL)
  if (.usable_path(from_global)) {
    return(.as_project_path(from_global))
  }
  rstudio_ok <- requireNamespace("rstudioapi", quietly = TRUE) &&
    rstudioapi::isAvailable()
  if (rstudio_ok) {
    path <- rstudioapi::getSourceEditorContext()$path
    if (.usable_path(path)) {
      return(.as_project_path(path))
    }
  }
  "unknown"
}

ggsave <- function(filename, plot = ggplot2::last_plot(), ...) {
  source_path <- .get_source_path()
  stamp <- paste0("Generated by: ", source_path)
  current_cap <- plot$labels$caption
  already_stamped <- isTRUE(grepl("Generated by:", current_cap, fixed = TRUE))
  if (!already_stamped) {
    new_cap <- if (is.null(current_cap) || !nchar(trimws(current_cap))) {
      stamp
    } else {
      paste0(current_cap, "\n", stamp)
    }
    plot <- plot + ggplot2::labs(caption = new_cap)
  }
  ggplot2::ggsave(filename, plot, ...)
}
